import type { Config } from './model';
import type { Layout, ResolvedPartition, ResolvedRamRegion } from './layout';
import { fileSafe, identSafe } from './validate';
import { formatAddr, formatHex, formatKb } from './units';

export interface OutFile {
  /** Unique tab key: "ld:<partition id>" or "file:memory_map.h" (prefixed so a partition id can never collide). */
  key: string;
  filename: string;
  content: string;
  lang: 'ld' | 'c';
}

/** Unique, file-system-safe base names (duplicates get _2, _3 …). */
export function baseNames(L: Layout): string[] {
  const used = new Set<string>();
  return L.partitions.map((p, i) => {
    let base = fileSafe(p.name) || `partition${i + 1}`;
    let cand = base;
    for (let n = 2; used.has(cand.toLowerCase()); n++) cand = `${base}_${n}`;
    used.add(cand.toLowerCase());
    base = cand;
    return base;
  });
}

/** The RAM region a partition links against in split mode: its assignment, else the first normal region. */
export function ramRegionFor(config: Config, L: Layout, partitionId: string): ResolvedRamRegion | undefined {
  const split = L.ram?.split ?? [];
  const wanted = config.partitions.find((q) => q.id === partitionId)?.ram;
  return split.find((r) => r.id === wanted && !r.noinit) ?? split.find((r) => !r.noinit);
}

function regionLine(config: Config, L: Layout, name: string, r: ResolvedRamRegion): string {
  const base = L.ram!.start;
  if (config.output.expressions && r.offset !== 0n) {
    return `  ${name} (xrw) : org = ${formatAddr(base)} + ${formatHex(r.offset)}, len = ${formatHex(r.endOffset)} - ${formatHex(r.offset)}`;
  }
  return `  ${name} (xrw) : org = ${formatAddr(r.start)}, len = ${formatHex(r.size)}`;
}

function ramLines(config: Config, L: Layout, partitionId: string): string[] {
  if (!L.ram) return [];
  if (L.ram.split.length) {
    const main = ramRegionFor(config, L, partitionId);
    const noinit = L.ram.split.find((r) => r.noinit);
    return [...(main ? [regionLine(config, L, 'RAM', main)] : []), ...(noinit ? [regionLine(config, L, 'RAM_NOINIT', noinit)] : [])];
  }
  const { start, size, reserved } = L.ram;
  const x = config.output.expressions;
  const usable = size - reserved;
  const lines: string[] = [];
  if (reserved > 0n) {
    lines.push(
      `  RAM (xrw) : org = ${formatAddr(start)}, len = ${x ? `${formatHex(size)} - ${formatHex(reserved)}` : formatHex(usable)}`,
      `  RAM_NOINIT (xrw) : org = ${x ? `${formatAddr(start)} + ${formatHex(size)} - ${formatHex(reserved)}` : formatAddr(start + usable)}, len = ${formatHex(reserved)}`,
    );
  } else {
    lines.push(`  RAM (xrw) : org = ${formatAddr(start)}, len = ${formatHex(size)}`);
  }
  return lines;
}

function romLine(config: Config, L: Layout, p: ResolvedPartition): string {
  const x = config.output.expressions;
  if (x && p.offset !== 0n) {
    return `  ROM (rx) : org = ${formatAddr(L.regionStart)} + ${formatHex(p.offset)}, len = ${formatHex(p.endOffset)} - ${formatHex(p.offset)}`;
  }
  return `  ROM (rx) : org = ${formatAddr(p.start)}, len = ${formatHex(p.size)}`;
}

function symbolLines(config: Config, L: Layout): string[] {
  const x = config.output.expressions;
  const names = baseNames(L);
  const out: string[] = [];
  L.partitions.forEach((p, i) => {
    const id = identSafe(names[i]).toLowerCase();
    if (x) {
      out.push(
        `PROVIDE(_${id}_start = ${formatAddr(p.start)});`,
        `PROVIDE(_${id}_size = ${formatHex(p.size)});`,
        `PROVIDE(_${id}_end = _${id}_start + _${id}_size);`,
      );
    } else {
      out.push(
        `PROVIDE(_${id}_start = ${formatAddr(p.start)});`,
        `PROVIDE(_${id}_size = ${formatHex(p.size)});`,
        `PROVIDE(_${id}_end = ${formatAddr(p.end)});`,
      );
    }
  });
  for (const r of L.ram?.split ?? []) {
    const id = `ram_${identSafe(r.name).toLowerCase()}`;
    if (x) {
      out.push(
        `PROVIDE(_${id}_start = ${formatAddr(r.start)});`,
        `PROVIDE(_${id}_size = ${formatHex(r.size)});`,
        `PROVIDE(_${id}_end = _${id}_start + _${id}_size);`,
      );
    } else {
      out.push(`PROVIDE(_${id}_start = ${formatAddr(r.start)});`, `PROVIDE(_${id}_size = ${formatHex(r.size)});`, `PROVIDE(_${id}_end = ${formatAddr(r.end)});`);
    }
  }
  return out;
}

function banner(config: Config, L: Layout, p: ResolvedPartition, mode: string): string[] {
  const rn = config.region.name.trim() || 'FLASH';
  const lines = [
    '/*',
    ` * Linker script for partition "${p.name}" — ${mode}`,
    ' * Generated by Linker Partition Planner.',
    ` * ${rn}: ${formatAddr(L.regionStart)}, ${formatHex(L.regionSize)} bytes = ${formatKb(L.regionSize)}${L.dual ? `, dual-bank (2 × ${formatKb(L.bankSize)})` : ''}`,
    ` * ${p.name}: ${formatAddr(p.start)} .. ${formatAddr(p.end - 1n)}, ${formatHex(p.size)} bytes = ${formatKb(p.size)}`,
  ];
  if (L.dual && p.inactiveStart !== null) {
    lines.push(
      ` * Uses bank 1 addresses (the code runs here after a bank swap too).`,
      ` * Inactive bank copy for update uploads: ${formatAddr(p.inactiveStart)} .. ${formatAddr(p.inactiveStart + p.size - 1n)}`,
    );
  }
  const region = L.ram?.split.length ? ramRegionFor(config, L, p.id) : undefined;
  if (region) lines.push(` * RAM region "${region.name}": ${formatAddr(region.start)} .. ${formatAddr(region.end - 1n)}, ${formatHex(region.size)} bytes = ${formatKb(region.size)}`);
  lines.push(' */');
  return lines;
}

const FULL_TEMPLATE = `/* Entry point */
ENTRY(Reset_Handler)

/* Highest address of the user stack (top of usable RAM) */
_estack = ORIGIN(RAM) + LENGTH(RAM);

/* Minimum heap/stack; the link fails if RAM cannot hold them */
_Min_Heap_Size  = 0x200;
_Min_Stack_Size = 0x400;

SECTIONS
{
  /* Vector table first, at the start of this partition */
  .isr_vector :
  {
    . = ALIGN(4);
    KEEP(*(.isr_vector))
    . = ALIGN(4);
  } >ROM

  .text :
  {
    . = ALIGN(4);
    *(.text)
    *(.text*)
    *(.glue_7)
    *(.glue_7t)
    *(.eh_frame)
    KEEP(*(.init))
    KEEP(*(.fini))
    . = ALIGN(4);
    _etext = .;
  } >ROM

  .rodata :
  {
    . = ALIGN(4);
    *(.rodata)
    *(.rodata*)
    . = ALIGN(4);
  } >ROM

  .ARM.extab (READONLY) : { *(.ARM.extab* .gnu.linkonce.armextab.*) } >ROM
  .ARM : {
    __exidx_start = .;
    *(.ARM.exidx*)
    __exidx_end = .;
  } >ROM

  .preinit_array (READONLY) :
  {
    PROVIDE_HIDDEN(__preinit_array_start = .);
    KEEP(*(.preinit_array*))
    PROVIDE_HIDDEN(__preinit_array_end = .);
  } >ROM

  .init_array (READONLY) :
  {
    PROVIDE_HIDDEN(__init_array_start = .);
    KEEP(*(SORT(.init_array.*)))
    KEEP(*(.init_array*))
    PROVIDE_HIDDEN(__init_array_end = .);
  } >ROM

  .fini_array (READONLY) :
  {
    PROVIDE_HIDDEN(__fini_array_start = .);
    KEEP(*(SORT(.fini_array.*)))
    KEEP(*(.fini_array*))
    PROVIDE_HIDDEN(__fini_array_end = .);
  } >ROM

  /* Load address of .data in ROM, used by the startup code */
  _sidata = LOADADDR(.data);

  .data :
  {
    . = ALIGN(4);
    _sdata = .;
    *(.data)
    *(.data*)
    *(.RamFunc)
    *(.RamFunc*)
    . = ALIGN(4);
    _edata = .;
  } >RAM AT> ROM

  .bss :
  {
    . = ALIGN(4);
    _sbss = .;
    __bss_start__ = _sbss;
    *(.bss)
    *(.bss*)
    *(COMMON)
    . = ALIGN(4);
    _ebss = .;
    __bss_end__ = _ebss;
  } >RAM
@NOINIT@
  /* Checks that heap + stack fit into RAM */
  ._user_heap_stack :
  {
    . = ALIGN(8);
    PROVIDE(end = .);
    PROVIDE(_end = .);
    . = . + _Min_Heap_Size;
    . = . + _Min_Stack_Size;
    . = ALIGN(8);
  } >RAM

  /DISCARD/ :
  {
    libc.a ( * )
    libm.a ( * )
    libgcc.a ( * )
  }

  .ARM.attributes 0 : { *(.ARM.attributes) }
}
`;

const NOINIT_SECTION = `
  /* Shared no-init area (e.g. flags passed between bootloader and application) */
  .noinit (NOLOAD) :
  {
    . = ALIGN(4);
    KEEP(*(.noinit))
    KEEP(*(.noinit*))
    . = ALIGN(4);
  } >RAM_NOINIT
`;

export function generateLdFiles(config: Config, L: Layout): OutFile[] {
  const names = baseNames(L);
  const full = config.output.mode === 'full';
  return L.partitions.map((p, i) => {
    const mode = full
      ? 'complete Cortex-M template (STARTING POINT — review and adapt before use)'
      : 'MEMORY block only (paste into your generated linker script)';
    const parts: string[] = [banner(config, L, p, mode).join('\n'), ''];
    parts.push('MEMORY', '{', romLine(config, L, p), ...ramLines(config, L, p.id), '}');
    if (config.output.symbols && L.partitions.length) {
      parts.push('', '/* Partition symbols (usable from C via extern) */', ...symbolLines(config, L));
    }
    if (full) {
      const hasNoinit = L.ram && (L.ram.split.length ? L.ram.split.some((r) => r.noinit) : L.ram.reserved > 0n);
      const noinit = hasNoinit ? NOINIT_SECTION : '';
      parts.push('', FULL_TEMPLATE.replace('@NOINIT@', noinit).trimEnd());
    }
    return { key: `ld:${p.id}`, filename: `${names[i]}.ld`, content: parts.join('\n') + '\n', lang: 'ld' as const };
  });
}

export function generateHeader(config: Config, L: Layout): OutFile {
  const names = baseNames(L);
  const rn = identSafe(config.region.name.trim() || 'FLASH').toUpperCase();
  const def = (name: string, value: bigint, comment?: string) => {
    const v = name.includes('SIZE') || name.endsWith('_PAGE') ? formatHex(value) : formatAddr(value);
    return `#define ${name.padEnd(34)} ${(v + 'UL').padEnd(14)}${comment ? ` /* ${comment} */` : ''}`.trimEnd();
  };
  const lines: string[] = [
    '/*',
    ' * memory_map.h — generated by Linker Partition Planner.',
    ' * Single source of truth for the flash layout; include from bootloader and application.',
    ' * *_END values are exclusive (first address after the partition).',
    ' */',
    '#ifndef MEMORY_MAP_H',
    '#define MEMORY_MAP_H',
    '',
    def(`${rn}_START`, L.regionStart),
    def(`${rn}_SIZE`, L.regionSize, formatKb(L.regionSize)),
    def(`${rn}_END`, L.regionStart + L.regionSize),
    def(`${rn}_PAGE_SIZE`, L.page, formatKb(L.page)),
  ];
  if (L.dual) {
    lines.push(
      def(`${rn}_BANK_SIZE`, L.bankSize, formatKb(L.bankSize)),
      def(`${rn}_BANK1_START`, L.bankStarts[0]),
      def(`${rn}_BANK2_START`, L.bankStarts[1]),
    );
  }
  L.partitions.forEach((p, i) => {
    const id = identSafe(names[i]).toUpperCase();
    lines.push('', `/* ${p.name}${L.dual ? ` — ${p.kind === 'shared' ? 'identical in both banks' : 'update target'}` : ''} */`);
    lines.push(def(`PART_${id}_START`, p.start), def(`PART_${id}_SIZE`, p.size, formatKb(p.size)), def(`PART_${id}_END`, p.end));
    if (L.dual && p.inactiveStart !== null) {
      lines.push(
        def(`PART_${id}_INACTIVE_START`, p.inactiveStart, 'other bank, for update uploads'),
        def(`PART_${id}_INACTIVE_END`, p.inactiveStart + p.size),
      );
    }
  });
  if (L.ram) {
    lines.push('', '/* RAM */', def('RAM_START', L.ram.start), def('RAM_SIZE', L.ram.size, formatKb(L.ram.size)));
    if (L.ram.reserved > 0n) {
      lines.push(
        def('RAM_NOINIT_START', L.ram.start + L.ram.size - L.ram.reserved, 'shared no-init area'),
        def('RAM_NOINIT_SIZE', L.ram.reserved),
      );
    }
    for (const r of L.ram.split) {
      const id = identSafe(r.name).toUpperCase();
      lines.push(
        '',
        `/* RAM region ${r.name}${r.noinit ? ' — shared no-init area' : ''} */`,
        def(`RAM_REGION_${id}_START`, r.start),
        def(`RAM_REGION_${id}_SIZE`, r.size, formatKb(r.size)),
        def(`RAM_REGION_${id}_END`, r.end),
      );
      if (r.noinit) lines.push(def('RAM_NOINIT_START', r.start), def('RAM_NOINIT_SIZE', r.size));
    }
  }
  lines.push('', '#endif /* MEMORY_MAP_H */', '');
  return { key: 'file:memory_map.h', filename: 'memory_map.h', content: lines.join('\n'), lang: 'c' };
}

export const generateAll = (config: Config, L: Layout): OutFile[] => [...generateLdFiles(config, L), generateHeader(config, L)];
